import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { differentialCases } from '../fixtures/differential-corpus.mjs'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const output = path.join(root, 'src/rules/differential-tree.generated.tsx')
const perturbCompiledTier =
  process.env.TAMAGUI_DIFFERENTIAL_PERTURB === 'definition-width'

const payload = (case_) =>
  perturbCompiledTier && case_.id === 'definition-width' ? 74 : case_.payload

const literal = (value) =>
  typeof value === 'string' ? JSON.stringify(value) : `{${JSON.stringify(value)}}`

const prop = (name, value) => `${name}=${literal(value)}`

function declaration(case_, index) {
  if (case_.placement === 'definition') {
    return `const Differential${index} = styled(View, { ${case_.property}: ${JSON.stringify(payload(case_))} })`
  }
  if (case_.placement === 'styled-call' || case_.placement === 'nested-definition') {
    const first = `const Differential${index}Base = styled(View, { ${case_.property}: ${JSON.stringify(case_.property === 'backgroundColor' ? '#7f1d1d' : 31)} })`
    if (case_.placement === 'nested-definition') {
      return `${first}\nconst Differential${index} = styled(Differential${index}Base, { ${case_.property}: ${JSON.stringify(payload(case_))} })`
    }
    return first
  }
  if (case_.placement === 'dynamic-prop') {
    return `const differential${index}Value = ${JSON.stringify(payload(case_))}`
  }
  return ''
}

function element(case_, index) {
  const attributes = [
    `data-testid=${JSON.stringify(`differential-${case_.id}`)}`,
    'data-differential-probe=""',
    `data-differential-id=${JSON.stringify(case_.id)}`,
    `data-differential-expected={${JSON.stringify(JSON.stringify(case_.expected))}}`,
    'minWidth={24}',
    'minHeight={24}',
  ]
  if (case_.action) {
    attributes.push(`data-differential-action=${JSON.stringify(case_.action)}`)
  }
  if (case_.expectedFailure) {
    attributes.push(
      `data-differential-expected-failure=${JSON.stringify(case_.expectedFailure)}`
    )
  }
  if (case_.action === 'focus') attributes.push('tabIndex={0}')

  let component = 'View'
  if (case_.placement === 'definition' || case_.placement === 'nested-definition') {
    component = `Differential${index}`
  } else if (case_.placement === 'styled-call') {
    component = `Differential${index}Base`
    attributes.push(prop(case_.property, payload(case_)))
  } else if (case_.placement === 'prop') {
    attributes.push(prop(case_.property, payload(case_)))
  } else if (case_.placement === 'dynamic-prop') {
    attributes.push(`${case_.property}={differential${index}Value}`)
  } else if (case_.placement === 'style-object') {
    attributes.push(`style={{ ${case_.property}: ${JSON.stringify(payload(case_))} }}`)
  } else if (case_.placement === 'style-array') {
    attributes.push(`style={[{ ${case_.property}: ${JSON.stringify(payload(case_))} }]}`)
  } else if (case_.placement === 'tailwind') {
    component = 'TailwindView'
    attributes.push(`className=${JSON.stringify(payload(case_))}`)
  } else {
    throw new Error(`unknown differential placement ${case_.placement}`)
  }

  let jsx = `<${component} ${attributes.join(' ')} />`
  if (case_.wrapper === 'dark') jsx = `<div className="t_dark">${jsx}</div>`
  if (case_.wrapper === 'group') {
    jsx = `<View group="card" data-differential-group="">${jsx}</View>`
  }
  return jsx
}

export function generateDifferentialTree() {
  const declarations = differentialCases.map(declaration).filter(Boolean).join('\n\n')
  const elements = differentialCases
    .map((case_, index) => `      ${element(case_, index)}`)
    .join('\n')
  writeFileSync(
    output,
    `// generated by scripts/generate-differential-tree.mjs from the curated corpus.\n// do not edit this file directly.\nimport { View, styled } from 'tamagui'\nimport { View as TailwindView } from '@tamagui/tailwind'\n\n${declarations}\n\nexport function DifferentialCorpus() {\n  return (\n    <View data-testid="differential-corpus" gap={2}>\n${elements}\n    </View>\n  )\n}\n`
  )
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateDifferentialTree()
}
