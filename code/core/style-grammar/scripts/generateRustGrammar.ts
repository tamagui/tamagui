// Generates the Rust grammar crate's modifier tables and its conformance
// vectors from this package.
//
// The Rust LSP had forked: `focusVisible`/`focusWithin` where the grammar spells
// them `focus-visible`/`focus-within`, no `active` alias, no group modifiers, no
// container modifiers. Nobody wrote them wrong: they were typed in once and the
// grammar moved. So they are no longer typed in: this script is the only way
// those tables change, and the vectors below are what makes the Rust parser
// prove it still agrees rather than merely look like it does.
//
//   bun scripts/generateRustGrammar.ts           write
//   bun scripts/generateRustGrammar.ts --check    fail if what is on disk differs
//
// Run from the package root. `--check` is what CI and the freshness test use.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

import { grammarPlatformNames } from '../src/config'
import {
  canonicalClauseModifier,
  parseGroupModifier,
  stateModifierNames,
} from '../src/clauseIdentity'
import { createModifierRegistry, parseContainerModifier } from '../src/modifierRegistry'
import { coreStateModifierNames, modifierAliases } from '../src/stateModifiers'
import { parseValue } from '../src/valueParser'
import { grammarMaxNonPlatformDepth } from '../src/valueTypes'
import {
  chaosAlphabet,
  constructCase,
  integer,
  mulberry32,
  registeredModifiers,
  unregisteredModifiers,
} from '../src/__tests__/valueCorpus'

// the config the vectors are resolved against. Small and fixed on purpose: a
// vector file that moved with a real app's config would stop being a contract.
const MEDIA_NAMES = ['sm', 'md', 'lg', 'gtMd', 'hoverNone']
const THEME_NAMES = ['light', 'dark', 'dark_blue']
const CONTAINER_SIZE_NAMES = ['sm', 'md', 'lg']

const { registry } = createModifierRegistry(
  {
    mediaNames: MEDIA_NAMES,
    themeNames: THEME_NAMES,
    platformNames: grammarPlatformNames,
  },
  { containerSizeNames: CONTAINER_SIZE_NAMES }
)

const packageRoot = join(dirname(new URL(import.meta.url).pathname), '..')
const crateRoot = join(packageRoot, '../../lsp/crates/tamagui-grammar')

const banner = `// @generated by @tamagui/style-grammar's scripts/generateRustGrammar.ts.
// Do not edit: run \`bun scripts/generateRustGrammar.ts\` in that package.
//
// These are the grammar's own tables, not a Rust reading of them. The crate is
// an editor transport for the flat value grammar and never a second owner of
// what a modifier means.
`

const rustStrings = (names: Iterable<string>): string =>
  [...names].map((name) => JSON.stringify(name)).join(', ')

function generatedRust(): string {
  const aliasPairs = Object.entries(modifierAliases)
    .map(
      ([alias, canonical]) => `(${JSON.stringify(alias)}, ${JSON.stringify(canonical)})`
    )
    .join(', ')
  return `${banner}
/// the core interaction and lifecycle modifiers, in grammar order
pub const CORE_STATE_MODIFIERS: &[&str] = &[${rustStrings(coreStateModifierNames)}];

/// every alternate spelling and the modifier it means
pub const MODIFIER_ALIASES: &[(&str, &str)] = &[${aliasPairs}];

/// every built-in runtime state spelling: core and aliases
pub const STATE_MODIFIERS: &[&str] = &[${rustStrings(stateModifierNames)}];

pub const PLATFORM_MODIFIERS: &[&str] = &[${rustStrings(grammarPlatformNames)}];

/// \`group-hover\` targets the nearest unnamed group, \`group-hover/card\` a named one
pub const GROUP_PREFIX: &str = "group-";

/// \`@sm\` targets the nearest container, \`@sm/card\` a named one, and no
/// configured name may take the prefix
pub const CONTAINER_PREFIX: char = '@';

/// how many distinct non-platform conditions one clause may encode
pub const MAX_NON_PLATFORM_DEPTH: usize = ${grammarMaxNonPlatformDepth};
`
}

interface ParseVector {
  source: string
  ok: boolean
  base?: string | null
  clauses?: Array<{ modifiers: string[]; payload: string }>
  errors?: Array<{ code: string; index: number }>
}

function parseVector(source: string): ParseVector {
  const result = parseValue(source, registry)
  if (!result.ok) {
    return {
      source,
      ok: false,
      errors: result.errors.map((error) => ({ code: error.code, index: error.index })),
    }
  }
  return {
    source,
    ok: true,
    base: result.value.base,
    clauses: result.value.clauses.map((clause) => ({
      modifiers: [...clause.modifiers],
      payload: clause.payload,
    })),
  }
}

/** the hand-written cases: every rule the two parsers used to disagree about */
const handWritten = [
  'background',
  'background hover:background-hover press:background-press',
  'dark:hover:sm:blue',
  'url(https://x.com/a.png)',
  'hover:url(https://x.com/a.png)',
  'rgba(1, 2, 3, 1) hover:rgba(4, 5, 6, 1)',
  'calc(100% - calc(2px + 1px))',
  'content:"a: b c"',
  '  a   hover:b  ',
  '4 sm:6',
  // multi-word payloads: a payload runs to the next clause word, not to the
  // next space. The Rust parser used to cut a clause at every space, which made
  // `solid` and `red` two more base clauses.
  '1px solid red',
  'hover:1px solid red',
  '2px dashed black hover:4px solid white',
  // brackets are not nesting. The Rust parser tracked `[` and `{` as depth,
  // so it read `[color:red]` as one payload where the grammar reads a clause
  // whose modifier is `[color`.
  'sm:[color:red]',
  'a{b',
  'a}b',
  'red; position: fixed',
  'red } .x { color: blue',
  '0 2px 8px #0003;',
  // a top-level backslash escapes the next character
  'none hover:custom\\:part',
  'safe\\;tail',
  'escaped\\ space',
  // delimiters left open
  'url("http://x.com',
  'linear-gradient(135deg, red',
  'red hover:"abc',
  // inside a string or a paren the refused characters are ordinary content
  'rgb(1;2)',
  'url(a;b)',
  'calc({)',
  'hover:rgb(1;2)',
  // modifier chain shapes
  'red hover:',
  'red hover::blue',
  'hver:red',
  '@xl:red',
  '@sm:red',
  '@sm/card:red',
  'group-hover:red',
  'group-hover/card:red',
  'group-wobble:red',
  // aliases the runtime used to spell out inline
  'active:red',
  'pressed:red',
  'starting:red',
  'ending:red',
  // comments are opaque content belonging to the segment they sit in, so a
  // colon inside one is not a clause boundary and a `;{}` inside one is not a
  // refused character. `red /* hover:x */ blue` is the case that used to split
  // into `red /*` plus a bogus `hover` clause, emitting a rule whose
  // unterminated comment swallowed the rules after it.
  'red /* hover:x */ blue',
  'red /* ; } { */ blue',
  'red hover:blue /* a:b */',
  'red hover:/*c*/blue',
  'calc(1px /* pad */ + 2px)',
  '/* leading */ red',
  '"/*" red',
  '/* " */ red',
  // a comment or a string left open swallows whatever follows it in the blob,
  // and a `*/` with nothing open closes one belonging to another rule
  'red/*',
  'red */ blue',
  'calc(1px /*',
  // `url()` is the one function CSS does not tokenize: no comments, no strings
  'url(a/*b.png)',
  'url(a"b.png)',
  'url("a/*b")',
  'myurl(a:b)',
  'image-set(url(a) 1x)',
  // the one value whose top-level colon is content
  '16:9',
  '',
  '   ',
]

function corpusVectors(): ParseVector[] {
  const out: ParseVector[] = []
  const random = mulberry32(0x9e3779b9)
  for (const mode of ['valid', 'unregistered', 'invalid'] as const) {
    for (let index = 0; index < 120; index++) {
      out.push(parseVector(constructCase(random, mode).source))
    }
  }
  // chaos: the parser must agree on strings nobody would write, because those
  // are the ones a fork shows up in
  const chaos = mulberry32(0xc0ffee)
  for (let index = 0; index < 240; index++) {
    const length = integer(chaos, 24)
    let source = ''
    for (let position = 0; position < length; position++) {
      source += chaosAlphabet[integer(chaos, chaosAlphabet.length)]
    }
    out.push(parseVector(source))
  }
  return out
}

function modifierVectors() {
  const names = new Set<string>([
    ...stateModifierNames,
    ...Object.keys(modifierAliases),
    ...grammarPlatformNames,
    ...MEDIA_NAMES,
    ...THEME_NAMES,
    ...registeredModifiers,
    ...unregisteredModifiers,
    'dark_blue',
    'group-hover',
    'group-press',
    'group-active',
    'group-pressed',
    'group-hover/card',
    'group-open',
    'group-',
    'group-hover/',
    'group-nonsense',
    '@sm',
    '@md/card',
    '@xl',
    '@',
    '@sm/',
    'hoverNone',
    'HOVER',
    'focusVisible',
    'focusWithin',
  ])
  return [...names].map((name) => {
    const group = parseGroupModifier(name)
    const container = parseContainerModifier(name)
    return {
      name,
      kind: registry.get(name) ?? null,
      canonical: canonicalClauseModifier(name),
      group: group ? { state: group.state, group: group.group } : null,
      container: container
        ? { size: container.size, container: container.container }
        : null,
    }
  })
}

function vectorsJson(): string {
  return `${JSON.stringify(
    {
      note: 'Generated by @tamagui/style-grammar scripts/generateRustGrammar.ts. Do not edit.',
      config: {
        mediaNames: MEDIA_NAMES,
        themeNames: THEME_NAMES,
        containerSizeNames: CONTAINER_SIZE_NAMES,
        platformNames: [...grammarPlatformNames],
      },
      modifiers: modifierVectors(),
      parse: [...handWritten.map(parseVector), ...corpusVectors()],
    },
    null,
    2
  )}\n`
}

const outputs: Array<[string, string]> = [
  [join(crateRoot, 'src/generated.rs'), generatedRust()],
  [join(crateRoot, 'tests/vectors.json'), vectorsJson()],
]

const check = process.argv.includes('--check')
let stale = false
for (const [path, contents] of outputs) {
  let current: string | null = null
  try {
    current = readFileSync(path, 'utf8')
  } catch {}
  if (current === contents) continue
  if (check) {
    stale = true
    console.error(`stale: ${path}`)
    continue
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, contents)
  console.log(`wrote ${path}`)
}

if (stale) {
  console.error('run `bun scripts/generateRustGrammar.ts` in code/core/style-grammar')
  process.exit(1)
}
