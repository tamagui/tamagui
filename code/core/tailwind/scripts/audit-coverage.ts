import { readFile } from 'node:fs/promises'
import path from 'node:path'

import { __unstable__loadDesignSystem } from 'tailwindcss'

import { defaultConfig } from '../../config/src/v6'
import { stylePropsAll } from '../../helpers/src/validStyleProps'
import { createTamagui } from '../../web/src/createTamagui'
import { resolveTailwindCandidate } from '../src/candidate'

type FamilyAudit = {
  total: number
  owned: number
  nativeReady: number
  unsafeOwned: number
  ownedCandidates: string[]
  unownedExamples: string[]
  unsafeExamples: string[]
}

type TargetAudit = {
  registrySize: number
  owned: number
  nativeReady: number
  unsafeOwned: number
  families: Record<string, FamilyAudit>
}

const repositoryRoot = path.resolve(import.meta.dir, '../../../..')
const themePath = path.join(repositoryRoot, 'node_modules/tailwindcss/theme.css')
const reportPath = path.join(repositoryRoot, 'plans/tailwind-coverage-audit.md')
const nativeBehaviorProps = new Set([
  'container',
  'containerType',
  'group',
  'numberOfLines',
])

async function auditTarget(): Promise<TargetAudit> {
  const theme = await readFile(themePath, 'utf8')
  const designSystem = await __unstable__loadDesignSystem(
    `${theme}\n@tailwind utilities;`
  )
  const config = createTamagui(defaultConfig as any)
  const families: Record<string, FamilyAudit> = {}
  let owned = 0
  let nativeReady = 0
  let unsafeOwned = 0

  for (const [candidate] of designSystem.getClassList()) {
    const parsed = designSystem.parseCandidate(candidate)[0]
    const family =
      parsed?.kind === 'arbitrary'
        ? `[${parsed.property}]`
        : parsed?.root || '(unclassified)'
    const audit = (families[family] ||= {
      total: 0,
      owned: 0,
      nativeReady: 0,
      unsafeOwned: 0,
      ownedCandidates: [],
      unownedExamples: [],
      unsafeExamples: [],
    })
    audit.total++

    const entries: Parameters<Parameters<typeof resolveTailwindCandidate>[2]>[0][] = []
    const preserveRaw = resolveTailwindCandidate(candidate, config, (entry) => {
      entries.push(entry)
    })
    if (preserveRaw !== false) {
      if (audit.unownedExamples.length < 3) audit.unownedExamples.push(candidate)
      continue
    }

    audit.owned++
    audit.ownedCandidates.push(candidate)
    owned++
    const unsupported = entries.find(
      ([property]) => !stylePropsAll[property] && !nativeBehaviorProps.has(property)
    )
    if (unsupported) {
      audit.unsafeOwned++
      unsafeOwned++
      if (audit.unsafeExamples.length < 3) {
        audit.unsafeExamples.push(`${candidate} → ${unsupported[0]}`)
      }
      continue
    }
    audit.nativeReady++
    nativeReady++
  }

  return {
    registrySize: designSystem.getClassList().length,
    owned,
    nativeReady,
    unsafeOwned,
    families,
  }
}

async function runWorker(target: 'web' | 'native'): Promise<TargetAudit> {
  const child = Bun.spawn([process.execPath, import.meta.path, `--target=${target}`], {
    cwd: import.meta.dir,
    env: { ...globalThis.process.env, TAMAGUI_TARGET: target },
    stdout: 'pipe',
    stderr: 'inherit',
  })
  const output = await new Response(child.stdout).text()
  const exitCode = await child.exited
  if (exitCode !== 0) throw new Error(`${target} coverage worker exited ${exitCode}`)
  return JSON.parse(output.trim().split('\n').at(-1)!)
}

async function writeReport(web: TargetAudit, native: TargetAudit) {
  if (web.registrySize !== native.registrySize) {
    throw new Error('Tailwind registry changed between target audits')
  }
  const familyNames = [
    ...new Set([...Object.keys(web.families), ...Object.keys(native.families)]),
  ].sort((a, b) => a.localeCompare(b))
  const completeFamilies = familyNames.filter(
    (family) => web.families[family].owned === web.families[family].total
  ).length
  const partialFamilies = familyNames.filter((family) => {
    const audit = web.families[family]
    return audit.owned > 0 && audit.owned < audit.total
  }).length
  const missingFamilies = familyNames.filter(
    (family) => web.families[family].owned === 0
  ).length
  const gated = web.owned - native.owned

  const lines = [
    '# Tailwind utility coverage audit',
    '',
    '> Generated by `bun run audit:coverage` in `code/core/tailwind`. Do not hand-edit.',
    '',
    'This audit derives its surface from Tailwind CSS 4.3.0 `getClassList()` with the',
    "installed default theme. It sends every candidate through Tamagui Tailwind's real",
    'frontend resolver once for web and once for native. “Web-owned” candidates become',
    'Tamagui atomics; unowned candidates remain available to the official Tailwind engine.',
    '“Native-ready” candidates are both claimed on native and restricted to properties in',
    "Tamagui's native runtime allowlist. Composer parts such as `from-*` count when the",
    'resolver accepts the part; runtime suites separately prove the complete multi-class value.',
    '',
    '## Snapshot',
    '',
    '| Metric | Count |',
    '| --- | ---: |',
    `| Tailwind default-theme candidates | ${web.registrySize.toLocaleString('en-US')} |`,
    `| Tamagui-owned candidates on web | ${web.owned.toLocaleString('en-US')} |`,
    `| Official-engine web fallback | ${(web.registrySize - web.owned).toLocaleString('en-US')} |`,
    `| Native-ready owned candidates | ${native.nativeReady.toLocaleString('en-US')} |`,
    `| Explicitly web-only / native-gated candidates | ${gated.toLocaleString('en-US')} |`,
    `| Unsafe native-owned candidates | ${native.unsafeOwned.toLocaleString('en-US')} |`,
    `| Complete / partial / missing web families | ${completeFamilies} / ${partialFamilies} / ${missingFamilies} |`,
    '',
    'Web coverage is the full registry: Tamagui-owned candidates use the shared style runtime',
    'and every remainder stays in `className` for the official engine. Native intentionally',
    'drops the remainder with a development warning. A nonzero unsafe count is an action item:',
    'the candidate needs a native lowering or an explicit target gate.',
    '',
    '## Family matrix',
    '',
    '| Tailwind family | Registry | Web-owned | Native-ready | Native-gated | Unsafe native | Gap examples |',
    '| --- | ---: | ---: | ---: | ---: | ---: | --- |',
  ]

  for (const family of familyNames) {
    const webAudit = web.families[family]
    const nativeAudit = native.families[family]
    const nativeOwned = new Set(nativeAudit.ownedCandidates)
    const gatedCandidates = webAudit.ownedCandidates.filter(
      (candidate) => !nativeOwned.has(candidate)
    )
    const examples = [
      ...nativeAudit.unsafeExamples,
      ...gatedCandidates.slice(0, 3).map((candidate) => `${candidate} (web-only)`),
      ...webAudit.unownedExamples,
    ]
      .slice(0, 3)
      .map((value) => `\`${value.replaceAll('|', '\\|')}\``)
      .join(', ')
    lines.push(
      `| \`${family.replaceAll('|', '\\|')}\` | ${webAudit.total} | ${webAudit.owned} | ${nativeAudit.nativeReady} | ${gatedCandidates.length} | ${nativeAudit.unsafeOwned} | ${examples} |`
    )
  }

  await Bun.write(reportPath, `${lines.join('\n')}\n`)
  console.log(
    `Tailwind ${web.registrySize}: ${web.owned} web-owned, ${native.nativeReady} native-ready, ${gated} gated, ${native.unsafeOwned} unsafe; wrote ${path.relative(repositoryRoot, reportPath)}`
  )
}

const target = process.argv.find((argument) => argument.startsWith('--target='))?.slice(9)
if (target) {
  console.log(JSON.stringify(await auditTarget()))
} else {
  const [web, native] = await Promise.all([runWorker('web'), runWorker('native')])
  await writeReport(web, native)
}
