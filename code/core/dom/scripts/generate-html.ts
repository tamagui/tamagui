/**
 * Generates the regular-Tamagui `html` namespace into
 * `code/core/web/src/dom/html.tsx`, from the tables.
 *
 *   bun scripts/generate-html.ts
 *
 * It is generated rather than written because the alternative is reading the
 * tag tables at runtime, which would put `@tamagui/dom` in `@tamagui/web`'s
 * runtime graph for every app that imports `html`. The tables are a build-time
 * contract; nothing about a tag changes while the app runs, so the element
 * defaults belong inlined in the source. A test regenerates this and fails if
 * the checked-in copy is stale.
 *
 * On web each tag is an ordinary Tamagui component rendering the literal
 * element, so it gets the whole regular Tamagui prop surface plus the strict
 * DOM props for that tag. On native the compiler rewrites these to the DOM
 * primitives, and a build with no compiler fails rather than rendering: see
 * `html.native.tsx`.
 */

import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { DISPLAY_WEB_RESET, TAGS, TAG_NAMES, TAG_WEB_DEFAULTS } from '../src/tables/tags'
import type { TagName } from '../src/tables/types'

/** the props interface each tag's generated component accepts */
const PROPS_INTERFACE: Readonly<Record<string, string>> = {
  common: 'StrictDOMProps',
  anchor: 'StrictDOMAnchorProps',
  button: 'StrictDOMButtonProps',
  image: 'StrictDOMImageProps',
  input: 'StrictDOMInputProps',
  label: 'StrictDOMLabelProps',
  listitem: 'StrictDOMListItemProps',
  optgroup: 'StrictDOMOptionGroupProps',
  option: 'StrictDOMOptionProps',
  select: 'StrictDOMSelectProps',
  textarea: 'StrictDOMTextAreaProps',
}

const propsFor = (tag: TagName) =>
  TAGS[tag].props === 'common' && TAGS[tag].content === 'void'
    ? 'StrictDOMVoidProps'
    : PROPS_INTERFACE[TAGS[tag].props]

/** the element defaults for one tag, as Tamagui style props */
const defaultsFor = (tag: TagName) => ({
  ...DISPLAY_WEB_RESET[TAGS[tag].display],
  ...TAGS[tag].defaults,
  ...TAG_WEB_DEFAULTS[tag],
})

const literal = (value: string | number) =>
  typeof value === 'number' ? `${value}` : `'${value}'`

export function generateHtml(): string {
  const components = TAG_NAMES.map((tag) => {
    const { backing } = TAGS[tag]
    const isText = backing !== 'view' && backing !== 'image'
    const base = isText ? 'textStaticConfig' : 'viewStaticConfig'
    const element = isText ? 'TamaguiTextElement' : 'TamaguiElement'
    const props = isText ? 'TextProps' : 'ViewProps'
    const nonStyle = isText ? 'TextNonStyleProps' : 'StackNonStyleProps'
    const styleBase = isText ? 'TextStylePropsBase' : 'StackStyleBase'
    const defaults = Object.entries(defaultsFor(tag))
      .map(([key, value]) => `${key}: ${literal(value)}`)
      .join(', ')

    return [
      `const ${tag} = createComponent<`,
      `  ${propsFor(tag)} & ${props},`,
      `  ${element},`,
      `  ${propsFor(tag)} & ${nonStyle},`,
      `  ${styleBase}`,
      `>({`,
      `  ...${base},`,
      `  Component: tag('${tag}'),`,
      `  componentName: '${tag}',`,
      // a text-entry control takes the text style props and the native input path
      ...(backing === 'textinput' ? ['  isInput: true,'] : []),
      `  defaultProps: { ...${base}.defaultProps${defaults ? `, ${defaults}` : ''} },`,
      `})`,
    ].join('\n')
  })

  const interfaces = [
    ...new Set(TAG_NAMES.map(propsFor)),
  ].sort()

  return `${[
    '// Generated by @tamagui/dom scripts/generate-html.ts from the tables in',
    '// that package. Run `bun run generate:html` there after changing a table.',
    '// Do not edit by hand.',
    '',
    `import type {\n${interfaces.map((name) => `  ${name},`).join('\n')}\n} from '@tamagui/dom'`,
    '',
    `import { createComponent } from '../createComponent'`,
    `import type {`,
    `  StackNonStyleProps,`,
    `  StackStyleBase,`,
    `  StaticConfig,`,
    `  TamaguiElement,`,
    `  TamaguiTextElement,`,
    `  TextNonStyleProps,`,
    `  TextProps,`,
    `  TextStylePropsBase,`,
    `} from '../types'`,
    `import { textStaticConfig } from '../views/Text'`,
    `import type { ViewProps } from '../views/View'`,
    `import { viewStaticConfig } from '../views/View'`,
    '',
    '/**',
    " * `StaticConfig.Component` is typed for component values, but a literal tag",
    ' * string is what the web frontend renders and what `createComponent` already',
    ' * handles; `styled.a()` casts the same way.',
    ' */',
    `const tag = (name: string) => name as unknown as StaticConfig['Component']`,
    '',
    '/**',
    ' * The semantic elements of the Tamagui DOM contract.',
    ' *',
    ' * On web each one is an ordinary Tamagui component that renders the literal',
    ' * tag, so it takes the regular Tamagui style props as well as the strict DOM',
    " * props for that element. The element defaults below are the browser's own,",
    ' * applied explicitly so a page renders the same whether or not a css reset',
    ' * ran; `compatibility.ts` in `@tamagui/dom` records where they differ from',
    ' * React Strict DOM and why.',
    ' */',
    components.join('\n\n'),
    '',
    'export const html = {',
    TAG_NAMES.map((tag) => `  ${tag},`).join('\n'),
    '}',
    '',
  ].join('\n')}`
}

/**
 * The native half. Every member throws, and that is the whole design: on native
 * the compiler rewrites `html.*` into the DOM primitives before the app runs,
 * so a member that survives to render proves the compiler did not run. Failing
 * loudly with the tag named is the specified behaviour — silently rendering
 * something approximate is what the DOM contract exists to prevent.
 */
export function generateHtmlNative(): string {
  return `${[
    '// Generated by @tamagui/dom scripts/generate-html.ts from the tables in',
    '// that package. Run `bun run generate:html` there after changing a table.',
    '// Do not edit by hand.',
    '',
    '/**',
    ' * The semantic elements of the Tamagui DOM contract, on native.',
    ' *',
    ' * There is no runtime here. Tag classification, native primitive injection',
    ' * and literal text wrapping are structural rewrites the compiler performs at',
    ' * build time, and none of them can be done while the app runs. So on native',
    ' * the compiler is required, and reaching one of these means it did not run.',
    ' */',
    'const requireCompiler = (tag: string) => () => {',
    '  throw new Error(',
    '    `<html.${tag}> reached the runtime on native, which means the Tamagui ` +',
    "      `compiler did not run. DOM mode is a build-time contract on native: the ` +",
    '      `compiler classifies each tag, injects the native primitive it lowers to ` +',
    '      `and wraps literal text, none of which can happen at runtime. Add the ` +',
    '      `Tamagui compiler to the native build, or use the regular Tamagui ` +',
    '      `components instead of html.*.`',
    '  )',
    '}',
    '',
    'export const html = {',
    TAG_NAMES.map((tag) => `  ${tag}: requireCompiler('${tag}'),`).join('\n'),
    '}',
    '',
  ].join('\n')}`
}

/**
 * The standalone `tamagui/dom` namespace. Same 49 tags, but each one takes only
 * the strict DOM props for that element plus a `style` handle — no regular
 * Tamagui style props — and every member throws, because the standalone entry
 * is compile-only on both platforms. See `standalone.ts` for why.
 */
export function generateStandaloneHtml(): string {
  const interfaces = [...new Set(TAG_NAMES.map(propsFor))].sort()

  return `${[
    '// Generated by @tamagui/dom scripts/generate-html.ts from the tables in',
    '// that package. Run `bun run generate:html` there after changing a table.',
    '// Do not edit by hand.',
    '',
    `import type {\n${interfaces.map((name) => `  ${name},`).join('\n')}\n} from '@tamagui/dom'`,
    '',
    `import type { DOMStyleProps } from './standalone'`,
    `import { requireCompiler } from './standalone'`,
    '',
    '/**',
    ' * The semantic elements of the standalone Tamagui DOM entry.',
    ' *',
    ' * Each one accepts the strict DOM props for its element plus a `style()`',
    ' * handle, and nothing else — the regular Tamagui style props are not part',
    ' * of this entry. All of them throw: the compiler replaces them, so reaching',
    ' * one means it did not run.',
    ' */',
    'export const html = {',
    TAG_NAMES.map(
      (tag) =>
        `  ${tag}: requireCompiler('${tag}') as (props: ${propsFor(tag)} & DOMStyleProps) => never,`
    ).join('\n'),
    '}',
    '',
  ].join('\n')}`
}

if (import.meta.main) {
  const dom = join(import.meta.dirname, '..', '..', 'web', 'src', 'dom')
  writeFileSync(join(dom, 'html.tsx'), generateHtml())
  writeFileSync(join(dom, 'html.native.tsx'), generateHtmlNative())
  writeFileSync(join(dom, 'standaloneHtml.ts'), generateStandaloneHtml())
  console.info(
    `generated html.tsx, html.native.tsx and standaloneHtml.ts for ${TAG_NAMES.length} tags`
  )
}
